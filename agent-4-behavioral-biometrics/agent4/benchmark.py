"""Latency benchmark. Every number and the SLA verdict are computed from the measurements."""

from __future__ import annotations

import asyncio
import platform
import time
from pathlib import Path
from typing import Dict, List

import numpy as np

from agent4.config import DEFAULT_MODEL_DIR, DEFAULT_REPORT_DIR, Settings
from agent4.scorer import BehaviorScorer
from agent4.simulation import PROFILES, generate_session_timings

SLA_MS = 15.0


def _stats(samples_ms: List[float]) -> Dict[str, float]:
    a = np.asarray(samples_ms)
    return {"mean": float(a.mean()), "p50": float(np.percentile(a, 50)), "p95": float(np.percentile(a, 95)),
            "p99": float(np.percentile(a, 99)), "max": float(a.max())}


def run_benchmark(model_dir: Path = DEFAULT_MODEL_DIR, report_dir: Path = DEFAULT_REPORT_DIR,
                  iterations: int = 1000) -> Dict[str, object]:
    t0 = time.perf_counter()
    scorer = BehaviorScorer.from_dir(model_dir)
    cold_start_ms = (time.perf_counter() - t0) * 1000.0

    rng = np.random.default_rng(0)
    sessions = {n: generate_session_timings(rng, PROFILES["HUMAN_LIKE"], n) for n in (20, 100, 300)}

    results: Dict[str, Dict[str, float]] = {}
    for n, (flights, holds) in sessions.items():
        for _ in range(50):
            scorer.score("warm", flights.tolist(), holds.tolist())
        times = []
        for _ in range(iterations):
            t = time.perf_counter()
            scorer.score("bench", flights.tolist(), holds.tolist())
            times.append((time.perf_counter() - t) * 1000.0)
        results[f"in-process scoring, {n} keystrokes"] = _stats(times)

    # End-to-end through the real ASGI stack (routing, validation, auth, serialisation, logging).
    import httpx
    from agent4.service import create_app

    flights, holds = sessions[100]
    payload = {"session_id": "bench-session", "intervals": flights.tolist(), "hold_durations": holds.tolist()}

    async def http_round_trip() -> List[float]:
        app = create_app(Settings(model_dir=model_dir, log_level="WARNING"), scorer=scorer)
        async with app.router.lifespan_context(app):
            async with httpx.AsyncClient(transport=httpx.ASGITransport(app=app), base_url="http://bench") as client:
                for _ in range(50):
                    await client.post("/behavior/analyze", json=payload)
                times = []
                for _ in range(iterations):
                    t = time.perf_counter()
                    resp = await client.post("/behavior/analyze", json=payload)
                    times.append((time.perf_counter() - t) * 1000.0)
                    assert resp.status_code == 200
                return times

    results["HTTP request via ASGI, 100 keystrokes"] = _stats(asyncio.run(http_round_trip()))

    worst_p95 = max(r["p95"] for r in results.values())
    verdict = "WITHIN" if worst_p95 < SLA_MS else "OUTSIDE"
    lines = [
        "# Latency benchmark",
        "",
        f"Generated by `python -m agent4 benchmark` ({iterations:,} warm iterations per row). Numbers are measured, "
        "not typed; the verdict below is computed from them.",
        "",
        "## Environment",
        "",
        f"* OS: {platform.system()} {platform.release()} ({platform.machine()})",
        f"* Python: {platform.python_version()}",
        f"* CPU: {platform.processor() or 'unknown'}",
        f"* Model version: `{scorer.model_version}`",
        f"* Model load (cold start): **{cold_start_ms:.1f} ms**",
        "",
        "## Results (milliseconds)",
        "",
        "| Path | mean | p50 | p95 | p99 | max |",
        "|---|---|---|---|---|---|",
    ]
    for name, r in results.items():
        lines.append(f"| {name} | {r['mean']:.3f} | {r['p50']:.3f} | {r['p95']:.3f} | {r['p99']:.3f} | {r['max']:.3f} |")
    lines += [
        "",
        f"## Verdict against the {SLA_MS:.0f} ms target",
        "",
        f"Worst p95 across all paths: **{worst_p95:.3f} ms** → **{verdict}** the {SLA_MS:.0f} ms target.",
        "",
        "The HTTP row uses an in-process ASGI transport, so it excludes network and TLS time. Measure the deployed "
        "path (load balancer, TLS, network hop) separately before quoting an end-to-end latency to the platform.",
    ]
    report_dir = Path(report_dir)
    report_dir.mkdir(parents=True, exist_ok=True)
    (report_dir / "latency_benchmark.md").write_text("\n".join(lines), encoding="utf-8")
    return {"cold_start_ms": cold_start_ms, "results": results, "worst_p95_ms": worst_p95, "verdict": verdict}
