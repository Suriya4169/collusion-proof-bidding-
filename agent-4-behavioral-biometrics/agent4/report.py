"""Generates ``evaluation_report.md`` from ``metrics.json`` so no number is ever typed by hand."""

from __future__ import annotations

from pathlib import Path
from typing import Dict, List

from agent4.simulation import ATTACK_CLASSES, NORMAL_CLASSES, PROFILES, STRESS_ATTACK_CLASSES

LABELS = {
    "HUMAN_LIKE": "Typical human",
    "FAST_HUMAN_LIKE": "Fast human",
    "SLOW_HUMAN_LIKE": "Slow human",
    "REGULAR_AUTOMATION": "Regular script",
    "BURST_AUTOMATION": "Burst injection",
    "ADAPTIVE_AUTOMATION": "Adaptive bot",
    "MIMIC_BOT": "Mimic bot (stress test)",
}


def _pct(x: float, digits: int = 1) -> str:
    return f"{x * 100:.{digits}f}%"


def _cell(r: Dict[str, object]) -> str:
    lo, hi = r["ci95"]
    return f"{_pct(r['rate'])} ({_pct(lo)}–{_pct(hi)})"


def _table(header: List[str], rows: List[List[str]]) -> str:
    out = ["| " + " | ".join(header) + " |", "|" + "|".join("---" for _ in header) + "|"]
    out += ["| " + " | ".join(r) + " |" for r in rows]
    return "\n".join(out)


def _length_table(mode: Dict[str, object]) -> str:
    buckets = list(mode["human_test"]["by_length"].keys())
    header = ["Keystrokes"] + [f"{b}" for b in buckets]
    rows = [["Genuine human (false alarms)"] + [_pct(mode["human_test"]["by_length"][b]["rate"]) for b in buckets]]
    for cls in ATTACK_CLASSES + STRESS_ATTACK_CLASSES:
        rows.append([LABELS[cls]] + [_pct(mode["attacks"][cls]["by_length"][b]["rate"], 0) for b in buckets])
    return _table(header, rows)


def _class_table(mode: Dict[str, object]) -> str:
    rows = []
    for style in NORMAL_CLASSES:
        r = mode["human_test"]["by_style"][style]
        rows.append([LABELS[style], "genuine human", str(r["n"]), _cell(r), "—"])
    for cls in ATTACK_CLASSES + STRESS_ATTACK_CLASSES:
        a = mode["attacks"][cls]
        role = "automation (stress test)" if PROFILES[cls].role == "stress_attack" else "automation"
        rows.append([LABELS[cls], role, str(a["overall"]["n"]), _cell(a["overall"]), f"{a['auc_vs_human_test']:.3f}"])
    return _table(["Class", "Role", "Sessions", "Flagged (risk ≥ 50), 95% CI", "ROC-AUC vs. humans"], rows)


def write_evaluation_report(metrics: Dict[str, object], selection: Dict[str, Dict[str, object]], path: Path,
                            with_figures: bool = True) -> Path:
    full, flight = metrics["full"], metrics["flight_only"]
    s, sf = full["summary"], flight["summary"]
    ds = metrics["dataset"]
    lines: List[str] = []
    add = lines.append

    add("# Agent 4 — Evaluation report")
    add("")
    add(f"Model version `{metrics['model_version']}` · generated by `python -m agent4 all` · "
        "every number below is read from `reports/metrics.json`.")
    add("")
    add("> **Read this first.** All data are *synthetic* timing sessions produced by `agent4/simulation.py`. "
        "These results show the pipeline is correct and how the detector behaves on the simulated world; they do not "
        "prove performance against real bidders or real bots. See *Limitations* and the model card.")
    add("")
    add("## 1. Protocol")
    add("")
    add(f"* {ds['total_sessions']:,} sessions, seed {ds['seed']}, {ds['min_events']}–{ds['max_events']} keystrokes each "
        "(log-uniform lengths, so short and long sessions are both common).")
    add("* **Genuine humans** (typical, fast, slow typists) are split "
        f"{ds['split_fractions']['train']:.0%} train / {ds['split_fractions']['calibration']:.0%} calibration / "
        f"{ds['split_fractions']['test']:.0%} test, by session. The detector is fitted on *train* only; the threshold and "
        "risk scale come from the disjoint *calibration* split; every human rate below is measured on *test*, so it is a "
        "genuine out-of-sample estimate (not true by construction).")
    add("* **Automation** classes never appear in training or calibration; they are used only to measure detection.")
    add("* The detector family and size were chosen on a *separate development dataset* (different seed), never on these "
        "test sessions. See section 6.")
    add("* A session is **flagged** when its risk score is ≥ 50 (more atypical than 95% of genuine humans of similar length). "
        "Intervals are 95% Wilson confidence intervals.")
    add("")
    add("## 2. Headline results (full model: hold + flight timing)")
    add("")
    add(_table(
        ["Measure", "Value"],
        [
            ["Genuine-human false-alarm rate (test, risk ≥ 50)", _cell(full["human_test"]["overall"])],
            ["Genuine humans in the HIGH band (risk ≥ 75)", _cell(full["human_test"]["high_anomaly_rate"])],
            ["Macro detection rate, three core attacks", _pct(s["macro_detection_rate_core_attacks"])],
            ["ROC-AUC, core attacks vs. humans", f"{s['roc_auc_core_attacks_vs_human']:.3f} "
                                                 f"(95% CI {s['roc_auc_ci95'][0]:.3f}–{s['roc_auc_ci95'][1]:.3f})"],
        ],
    ))
    add("")
    add(_class_table(full))
    add("")
    if with_figures:
        add("![Share of sessions flagged, by class](figures/01_flag_rate_by_class.png)")
        add("")
    add("## 3. Reliability grows with session length")
    add("")
    add("Percentages are the share of sessions flagged at each length. A short session carries little timing evidence, "
        "so the adaptive and mimic bots are hard to separate from humans until a few dozen keystrokes have been seen. "
        "The API reports this as `reliability` (`low` < 30, `medium` 30–99, `high` ≥ 100 keystrokes).")
    add("")
    add(_length_table(full))
    add("")
    if with_figures:
        add("![Flag rate by session length](figures/02_flag_rate_by_session_length.png)")
        add("")
        add("![Length-aware thresholds](figures/06_length_aware_thresholds.png)")
        add("")
    add("## 4. What a flag is worth in practice")
    add("")
    add("When bots are rare, most flags are false alarms, however good the detector. Precision at three assumed "
        "base rates (share of sessions that are automated), using the measured rates above:")
    add("")
    ppv, ppv_h = s["precision_at_prevalence"], s["precision_high_band_at_prevalence"]
    add(_table(
        ["Assumed share of sessions that are automated", "Precision of MODERATE+HIGH (risk ≥ 50)",
         "Precision of HIGH only (risk ≥ 75)"],
        [[k, _pct(ppv[k]), _pct(ppv_h[k])] for k in ppv],
    ))
    add("")
    add("This is why the service emits a *signal for human review* and never blocks a bid: use HIGH for priority review "
        "and combine with other evidence before acting.")
    add("")
    if with_figures:
        add("![Risk band mix per class](figures/03_risk_band_mix.png)")
        add("")
        add("![ROC](figures/04_roc_core_attacks.png)")
        add("")
    add("## 5. Flight-only fallback")
    add("")
    add("Used when a client can send only inter-key intervals (no hold times). With no hold-time information the "
        "adaptive bot is not distinguishable from humans, which is an inherent limit of that mode, not a tuning problem.")
    add("")
    add(_table(
        ["Measure", "Value"],
        [
            ["Genuine-human false-alarm rate (test)", _cell(flight["human_test"]["overall"])],
            ["Macro detection rate, three core attacks", _pct(sf["macro_detection_rate_core_attacks"])],
            ["ROC-AUC, core attacks vs. humans", f"{sf['roc_auc_core_attacks_vs_human']:.3f}"],
        ],
    ))
    add("")
    add(_class_table(flight))
    add("")
    add("## 6. Detector selection (development data, seed "
        f"{selection['full']['dev_seed']})")
    add("")
    add("Criterion: " + selection["full"]["criterion"] + ".")
    add("")
    for mode in ("full", "flight_only"):
        sel = selection[mode]
        add(f"**{mode}** — selected `{sel['selected']}`")
        add("")
        rows = []
        for name, r in sel["candidates"].items():
            d = r["detection_rate"]
            rows.append([name, _pct(r["human_test_fpr"]),
                         _pct(d["REGULAR_AUTOMATION"], 0), _pct(d["BURST_AUTOMATION"], 0),
                         _pct(d["ADAPTIVE_AUTOMATION"], 0), _pct(r["macro_detection_core_attacks"]),
                         _pct(d["MIMIC_BOT"], 0)])
        add(_table(["Detector", "Human FPR", "Regular", "Burst", "Adaptive", "Macro (core)", "Mimic (info only)"], rows))
        add("")
    add("Isolation Forest was the v1 detector. It needs the anomaly to be extreme along many features at once, so it "
        "misses bots that differ from humans only in the *shape* of their timing distribution. A mixture density over "
        "log-transformed features uses that evidence directly, and exports to plain NumPy arrays (no pickle, no "
        "scikit-learn at serving time).")
    add("")
    add("## 7. A typing style the model has never seen")
    add("")
    add("Each human style was withheld in turn: the model was refitted and recalibrated on the other two styles, then "
        "asked to score the withheld style.")
    add("")
    rows = []
    for style, r in metrics["leave_one_style_out"].items():
        rows.append([LABELS[style], _cell(r["seen_style_test_flagged"]), _cell(r["held_out_style_flagged"])])
    add(_table(["Withheld style", "Trained-on styles flagged (test)", "Withheld style flagged"], rows))
    add("")
    add("**Consequence:** the model defines *normal* as the typing styles it was trained on. A genuine style outside "
        "that population is flagged. Before deployment, retrain and recalibrate on real, representative bidder "
        "sessions (`python -m agent4 retrain`), and monitor the live share of flagged sessions: it should sit near 5%.")
    add("")
    if with_figures:
        add("![Unseen typing style](figures/05_unseen_typing_style.png)")
        add("")
    add("## 8. Limitations")
    add("")
    add("* Synthetic data from one generator: absolute numbers will change on real data. The *relative* findings "
        "(length dependence, shape features, the need for population-representative training) are the transferable part.")
    add("* The mimic bot, which copies human mean/spread/pause rate, is only partly detected. A replay of recorded human "
        "timing would be harder still; it needs sequence-level or non-timing signals.")
    add("* Hardware, keyboard, browser timer resolution and field type (numeric amount vs. free text) change real timing; "
        "none is modelled.")
    add("* The score is a statistical signal about timing, not evidence of fraud.")
    add("")

    path = Path(path)
    path.parent.mkdir(parents=True, exist_ok=True)
    path.write_text("\n".join(lines), encoding="utf-8")
    return path
