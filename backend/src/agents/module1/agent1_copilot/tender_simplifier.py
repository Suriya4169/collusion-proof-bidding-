from langchain_google_genai import ChatGoogleGenerativeAI
from langchain_core.prompts import PromptTemplate
from src.models.schemas import VerificationReport


def translate_summary(report: VerificationReport, target_language: str = "Hindi") -> str:
    """
    Sub-Agent 1.7: Tender Simplifier (Cross-Lingual).

    Takes the technical VerificationReport generated by the Symbolic Verifier
    and translates it into plain, actionable language that a non-technical
    small business owner can understand.

    Uses Gemini's native multilingual capabilities.
    """
    # 1. Initialize LLM
    llm = ChatGoogleGenerativeAI(model="gemini-2.5-pro")

    # 2. Build a human-readable summary of the checks for the prompt
    check_lines = []
    for check in report.checks:
        check_lines.append(
            f"- {check.rule_name}: {check.status.value} | "
            f"Required: {check.required_value}, Yours: {check.actual_value} | "
            f"Distance: {check.distance_pct:+.1f}% | {check.message}"
        )
    checks_text = "\n".join(check_lines)

    missing_text = ", ".join(report.missing_documents) if report.missing_documents else "None"

    # 3. Create a strict prompt for translation
    prompt_template = """
    You are a helpful government scheme advisor.
    
    Below is a technical eligibility report for an MSME (small business) applying
    for a government tender. Translate this into plain {language} that a small shop owner
    or factory owner can easily understand.
    
    RULES:
    1. Use simple, everyday {language} (mixed with English tech terms like "EMD", "turnover" is OK).
    2. DO NOT use complex legal jargon.
    3. Start with the overall result: eligible or not eligible.
    4. For each rule, explain in 1 simple sentence what it means for them.
    5. If there are missing documents, clearly tell them WHAT to get and WHERE to get it.
    6. End with one encouraging sentence.
    7. Keep the entire response under 200 words.
    
    === ELIGIBILITY REPORT ===
    Overall Result: {verdict}
    Compliance Score: {compliance_score}%
    
    Rule-by-Rule Checks:
    {checks}
    
    Missing Documents: {missing}
    === END REPORT ===
    
    Write the {language} summary below:
    """

    prompt = PromptTemplate(
        template=prompt_template,
        input_variables=["language", "verdict", "compliance_score", "checks", "missing"]
    )

    chain = prompt | llm

    verdict_str = "ELIGIBLE ✅" if report.is_eligible else "NOT ELIGIBLE ❌"

    result = chain.invoke({
        "language": target_language,
        "verdict": verdict_str,
        "compliance_score": report.overall_compliance_score,
        "checks": checks_text,
        "missing": missing_text,
    })

    # Extract the text content from the response
    # Gemini may return content as a string or as a list of parts
    if hasattr(result, 'content'):
        if isinstance(result.content, str):
            return result.content
        elif isinstance(result.content, list):
            # Gemini sometimes returns a list of dictionaries in newer versions
            text_parts = []
            for part in result.content:
                if isinstance(part, dict) and 'text' in part:
                    text_parts.append(part['text'])
                elif isinstance(part, str):
                    text_parts.append(part)
            return "".join(text_parts)
    return str(result)


def generate_plain_summary(report: VerificationReport) -> str:
    """
    Generates a plain-language English summary of the eligibility report.
    This is simpler than the Hindi translation — no API call needed.
    """
    lines = []

    if report.is_eligible:
        lines.append(f"✅ Good news! You ARE eligible to bid on this tender.")
        lines.append(f"Your overall compliance score is {report.overall_compliance_score}%.")
    else:
        lines.append(f"❌ Unfortunately, you are NOT eligible for this tender right now.")
        lines.append(f"Your overall compliance score is {report.overall_compliance_score}%.")

    lines.append("")

    for check in report.checks:
        if check.status == "PASS":
            lines.append(f"  ✅ {check.rule_name}: You meet this requirement.")
        elif check.status == "EXEMPTED":
            lines.append(f"  🟢 {check.rule_name}: You are EXEMPTED as a registered MSME!")
        else:
            lines.append(f"  ❌ {check.rule_name}: {check.message}")

    if report.missing_documents:
        lines.append("")
        lines.append("📋 Missing Documents:")
        for doc in report.missing_documents:
            lines.append(f"  ⚠️ You need: {doc}")

    return "\n".join(lines)
